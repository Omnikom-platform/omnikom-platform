// Dashboard screens generated from a site contract: what the client sees for each collection and page type.
//   node screens.mjs <site-contract.json> [--out screens.md]
// Every screen is derived (nothing hand-written per site or industry): list columns, filters, the editor's fields with
// their widget, required / locked / internal badges, where an item appears on the site, and the publish bar.
import { readFileSync, writeFileSync } from 'node:fs';
import { mergeCore, isMain } from './validate.mjs';

const WIDGET = {
  text: 'single line', richtext: 'rich text editor', slug: 'web address part (auto from title)', number: 'number', money: 'price ($)',
  boolean: 'tick box', date: 'date picker', datetime: 'date + time picker', enum: 'dropdown', email: 'email', phone: 'phone',
  url: 'link', image: 'photo upload (crop, alt text)', gallery: 'photo gallery (drag to reorder, pick cover)', file: 'file upload',
  reference: 'picker', address: 'address with autocomplete (fills map pin)', geo: 'map pin', list: 'repeatable rows', group: 'field group',
  seo: 'search preview (title + description)', sections: 'page sections',
};

function widget(f) {
  let w = WIDGET[f.type];
  if (f.type === 'enum') w += ` (${f.options.join(' / ')})`;
  if (f.type === 'reference') w = `${f.multiple ? 'multi-' : ''}picker from ${f.to}`;
  if (f.type === 'list' || f.type === 'group') w += f.open ? ' (free answers)' : `: ${Object.keys(f.of).join(', ')}`;
  if (f.media) w += ` (min ${f.media.minWidth || '-'}px${f.media.rightsConfirm ? ', "we have the right to publish" tick' : ''})`;
  if (f.sourced) w += ' + source link + date';
  return w;
}

function badges(f) {
  const b = [];
  if (f.required) b.push('required');
  if (f.locked) b.push(`LOCKED: ${f.locked.reason}`);
  if (f.internal) b.push('not shown on the site');
  if (f.visibleWhen) b.push(`shown on the site only when ${Object.entries(f.visibleWhen).map(([k, v]) => `${k} is ${v.join('/')}`).join(', ')}`);
  if (f.max && ['text', 'richtext'].includes(f.type)) b.push(`max ${f.max} chars`);
  return b.join('; ');
}

const fieldRows = fields => Object.entries(fields).map(([n, f]) => `| ${n} | ${widget(f)} | ${badges(f)} |`).join('\n');

export function screens(contract) {
  const cols = mergeCore(contract);
  const where = id => contract.placements.filter(p => p.collection === id).map(p => {
    const w = p.when ? ` when ${Object.entries(p.when).map(([k, v]) => `${k} is ${v.join('/')}`).join(', ')}` : '';
    if (p.to.sitemap) return `sitemap${w}`;
    if (p.to.schema) return `${p.to.schema} structured data on its page${w}`;
    const target = p.to.page ? `page ${p.to.page}` : `every ${p.to.pageType} page${p.to.match ? ` of its ${p.to.match}` : ''}`;
    return `${target} > ${p.to.section}${w}${p.limit ? ` (up to ${p.limit})` : ''}${p.sort ? `, sorted by ${p.sort.replace(/^-/, '')}${p.sort.startsWith('-') ? ' newest/highest first' : ''}` : ''}`;
  });
  const out = [`# Dashboard screens: ${contract.site.workspace}`, '',
    `Generated by \`contracts/screens.mjs\` from the site contract (industry: ${contract.site.industry}). Nothing on this page is written by hand.`, '',
    '## Menu', ''];
  const menu = Object.entries(cols).filter(([id]) => id !== 'pages');
  out.push(`- Pages (${contract.pages.length}, by type: ${Object.entries(contract.pages.reduce((a, p) => (a[p.type] = (a[p.type] || 0) + 1, a), {})).map(([t, n]) => `${t} ${n}`).join(', ')})`);
  for (const [id, c] of menu) out.push(`- ${c.label}${c.kind === 'singleton' ? ' (one form)' : c.kind === 'inbox' ? ' (inbox)' : ''}${c.access.member !== 'none' ? `: agents/members see ${c.access.member === 'own' ? 'only their own' : 'all'}` : ': owner + Omnikom only'}`);
  out.push('', 'Every content screen has the same publish bar: **Save draft** (a new version, the site does not change) · **Preview** · **Publish** (runs the checks below, rebuilds only this site) · **History** (every version with who and when; restore = a new version). Leads have no publish bar.', '');

  for (const [id, c] of menu) {
    out.push(`## ${c.label} \`${id}\``, '');
    if (c.kind === 'collection') {
      const cols2 = [c.titleField, c.statusField, c.ownerField && c.ownerField !== 'self' ? c.ownerField : null].filter(Boolean);
      const filters = Object.entries(c.fields).filter(([, f]) => f.type === 'enum' || (f.type === 'reference' && f.to !== 'team')).map(([n]) => n);
      out.push(`**List:** columns ${[...cols2, 'draft/published', 'last edited by'].join(' · ')}${filters.length ? `; filters ${filters.join(', ')}` : ''}; button "Add".`);
    }
    if (c.kind === 'inbox') out.push('**Inbox:** newest first; columns name · form · page · status · owner · received; actions: change status, assign, add note, export CSV, resend to CRM.');
    if (c.route) out.push(`**Public page:** ${c.route}`);
    const w = where(id);
    if (w.length) out.push(`**Appears on the site:** ${w.join('; ')}.`);
    out.push('', '| Field | Editor | Rules |', '|---|---|---|', fieldRows(c.fields), '');
  }

  out.push('## Page editors', '', 'A page\'s address and type come from the approved SEO plan and cannot be changed here. The client edits the text and photos of each "fields" section; "feed" sections fill themselves from the collections above; form and legal sections show what they contain but are edited elsewhere.', '');
  for (const [id, t] of Object.entries(contract.pageTypes)) {
    const n = contract.pages.filter(p => p.type === id).length;
    out.push(`### ${t.label} \`${id}\` (${n} page${n === 1 ? '' : 's'}${t.bind ? `, one per ${t.bind} item` : ''})`, '');
    for (const s of t.sections) {
      if (s.kind === 'fields') out.push(`- **${s.id}** (edit): ${Object.entries(s.fields).map(([fn, f]) => `${fn} [${widget(f)}${badges(f) ? '; ' + badges(f) : ''}]`).join(', ')}`);
      if (s.kind === 'feed') out.push(`- **${s.id}** (fills itself from ${cols[s.accepts].label})`);
      if (s.kind === 'form') out.push(`- **${s.id}** (form "${contract.forms[s.form].label || s.form}": ${Object.keys(contract.forms[s.form].fields).join(', ')}; answers go to the Lead inbox)`);
      if (s.kind === 'notice') out.push(`- **${s.id}** (legal text "${s.notice}", locked)`);
    }
    out.push('');
  }

  out.push('## Forms', '');
  for (const [id, f] of Object.entries(contract.forms)) {
    out.push(`- **${f.label || id}**: ${Object.entries(f.fields).map(([n, x]) => `${n}${x.required ? '*' : ''}`).join(', ')}; consent text from notices "${f.consent && f.consent.notice}" (locked)${f.crm ? `; sent to OmniSuite as ${Object.entries(f.crm).map(([a, b]) => `${a} -> "${b}"`).join(', ')}` : ''}`);
  }
  if ((contract.clientWording || []).length) {
    out.push('', '## Wording the client must confirm (goes into the review email)', '');
    for (const w of contract.clientWording) out.push(`- ${w.status} \`${w.where}\`: ${w.note || ''}`);
  }
  out.push('', '## Publish checks (from the contract, shown to the client in plain words when one fails)', '',
    '- Every required field filled; text within its length; no placeholder text ("[client to ...]", "TODO", "lorem ipsum").',
    '- Photos: alt text, wide enough, "we have the right to publish" ticked, location data stripped by the upload.',
    '- Facts and numbers shown to visitors carry a source link and date.',
    '- Locked text (licences, disclosures, consent) unchanged unless Omnikom recorded a sign-off.',
    '- Then the site checks (SEO gate, render gate); a failure deploys nothing.');
  return out.join('\n') + '\n';
}

if (isMain(import.meta.url)) {
  const [file, flag, outFile] = process.argv.slice(2);
  if (!file) { console.error('usage: node screens.mjs <site-contract.json> [--out screens.md]'); process.exit(2); }
  const md = screens(JSON.parse(readFileSync(file, 'utf8')));
  if (flag === '--out' && outFile) { writeFileSync(outFile, md); console.log(`wrote ${outFile} (${md.split('\n').length} lines)`); }
  else process.stdout.write(md);
}
