// design-engine: self-host OFL fonts (Omnikom design SOP; design.md step 4: fonts OFL, self-hosted). Fetches the Google Fonts CSS2 for
// each family (latin subset, variable weight range), downloads the woff2 files, and writes fonts.css with local relative URLs plus
// LICENSES.md. Nothing at run time loads from Google. Usage: node tools/design-engine/fetch-fonts.mjs <out dir> [--family "Name:axes"]...
import fs from 'node:fs';
import path from 'node:path';
const out = process.argv[2];
if (!out) { console.error('usage: <out dir> [--family "Name:axes"]...'); process.exit(2); }
fs.mkdirSync(out, { recursive: true });
// --family "Name:axes" (repeatable) replaces the default set, e.g. --family "Fraunces:ital,opsz,wght@0,9..144,300..800"
const custom = process.argv.slice(3).flatMap((x, i, arr) => (arr[i - 1] === '--family' ? [x.split(/:(.+)/).slice(0, 2)] : []));
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const DEFAULTS = [
  ['Fraunces', 'ital,opsz,wght@0,9..144,300..800;1,9..144,300..800'],
  ['Instrument Sans', 'ital,wght@0,400..700;1,400..700'],
  ['Inter Tight', 'ital,wght@0,300..800;1,300..800'],
  ['Manrope', 'wght@300..800'],
  ['Plus Jakarta Sans', 'ital,wght@0,300..800;1,300..800'],
  ['JetBrains Mono', 'wght@400..700'],
];
const FAMILIES = custom.length ? custom : DEFAULTS;
const get = async (u, text) => { const r = await fetch(u, { headers: { 'User-Agent': UA }, signal: AbortSignal.timeout(60000) }); if (!r.ok) throw new Error(`${r.status} ${u}`); return text ? r.text() : Buffer.from(await r.arrayBuffer()); };
let css = '/* Self-hosted OFL fonts (Google Fonts, SIL Open Font License 1.1), latin subset. Generated by tools/lead/fetch-fonts.mjs */\n';
const lic = ['# Font licences', '', 'All families are licensed under the SIL Open Font License 1.1 (https://openfontlicense.org), downloaded from Google Fonts 2026-10-27.', ''];
let files = 0;
for (const [fam, axes] of FAMILIES) {
  const src = await get(`https://fonts.googleapis.com/css2?family=${encodeURIComponent(fam)}:${axes}&display=swap`, true);
  const blocks = src.split('/*').filter((b) => /^\s*latin \*\//.test(b));
  for (const b of blocks) {
    const url = (b.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    const style = (b.match(/font-style:\s*(\w+)/) || [])[1];
    if (!url) continue;
    const name = `${fam.toLowerCase().replace(/ /g, '-')}-${style}.woff2`;
    fs.writeFileSync(path.join(out, name), await get(url));
    files++;
    css += b.replace(/^\s*latin \*\/\s*/, '').replace(url, name).trim() + '\n';
  }
  lic.push(`- ${fam}`);
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.writeFileSync(path.join(out, 'LICENSES.md'), lic.join('\n') + '\n');
console.log(`${files} woff2 files for ${FAMILIES.length} families -> ${out}/fonts.css`);
